def build_csv() -> bytes:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["规则名称", "类别", "严重级别", "规则说明/条件", "审核要点", "需法规依据", "是否启用"])
    for rid, name, cat, sev, desc, cps, legal in RULES:
        w.writerow([name, CAT_CN[cat], SEV_CN[sev], desc, "；".join(cps), "是" if legal else "否", "是"])
    return ("\ufeff" + buf.getvalue()).encode("utf-8-sig")


def build_replace_payload() -> dict:
    rules = []
    for rid, name, cat, sev, desc, cps, legal in RULES:
        rules.append({
            "id": rid, "name": name, "category": cat, "severity": sev,
            "description": desc, "checkpoints": cps,
            "need_legal_basis": legal, "enabled": True, "builtin": False,
        })
    return {
        "id": RULESET_ID, "name": RULESET_NAME,
        "description": f"决标审批流程风险预警审核规则集（仅审提供的结构化数据与评标相关附件，不审线下/评标委员会；共{len(rules)}条）",
        "builtin": False, "rules": rules,
    }


if __name__ == "__main__":
    import sys
    out = sys.argv[1] if len(sys.argv) > 1 else "decision_risk_rules.csv"
    with open(out, "wb") as f:
        f.write(build_csv())
    print(f"CSV written: {out} ({len(RULES)} rules)")
    jpath = os.path.splitext(out)[0] + ".json"
    with open(jpath, "w", encoding="utf-8") as f:
        json.dump(build_replace_payload(), f, ensure_ascii=False, indent=2)
    print(f"JSON(replace payload) written: {jpath}")
